// Altera somente fixtures de um servidor/banco dedicado de verificação.
// Requer playwright-core (NODE_PATH), TASK_TEST_BASE_URL e TASK_TEST_FIXTURES.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require('playwright-core');
const root = process.env.TASK_TEST_BASE_URL?.replace(/\/$/, '');
if (!root || !process.env.TASK_TEST_FIXTURES) throw new Error('Informe servidor e fixtures isolados.');
const fixture = JSON.parse(fs.readFileSync(process.env.TASK_TEST_FIXTURES, 'utf8'));
const output = process.env.TASK_TEST_SCREENSHOTS || '.private/browser-verification/screenshots';
fs.mkdirSync(output, {recursive:true});

(async () => {
  const browser = await chromium.launch({headless:true,
    executablePath:process.env.TASK_TEST_CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  try {
    const context = await browser.newContext({viewport:{width:1366,height:1000}});
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(root + '/');
    assert(await page.getByText('Infraestrutura', {exact:true}).count());
    assert.equal(await page.locator('.inova-equip-card').count(), 7);
    const publicImage = page.locator('.inova-equip-card img').first();
    await publicImage.scrollIntoViewIfNeeded();
    await page.waitForFunction(() => [...document.querySelectorAll('.inova-equip-card img')].some(image => image.complete && image.naturalWidth > 0));
    await page.screenshot({path:path.join(output,'infraestrutura-publica.png'),fullPage:true});
    await context.addCookies([{name:'sessionid',value:fixture.session,url:root}]);
    await page.goto(root + '/tarefas/');
    assert.equal(await page.locator(`[data-task-id="${fixture.old}"]`).count(), 0);
    await page.getByRole('link', {name:'Lista completa',exact:true}).click();
    await page.locator('[name=q]').fill('Tarefa de verificação 0');
    await page.getByRole('button', {name:'Aplicar filtros'}).click();
    assert(await page.getByRole('link', {name:new RegExp(`#${String(fixture.old).padStart(3,'0')} ·`)}).count());
    await page.getByRole('link', {name:'Limpar filtros'}).click();
    assert(await page.locator('table tbody tr').count() === 25);
    assert(await page.getByRole('link', {name:/Próxima/}).count());
    await page.screenshot({path:path.join(output,'lista-desktop.png'),fullPage:true});
    await page.goto(root + `/tarefas/${fixture.running}/`);
    const timer = page.locator('[data-task-timer]');
    let polls = 0;
    page.on('request', request => {if (request.url().includes('/api/')) polls++;});
    const before = await timer.textContent();
    await page.waitForTimeout(1200);
    assert.notEqual(await timer.textContent(), before, 'Criação deve contar no navegador');
    assert.equal(polls,0,'Relógio não consulta a API por segundo');
    await page.locator('[name=status]').selectOption('avaliacao');
    await page.getByRole('button', {name:'Salvar status'}).click();
    const paused = await timer.textContent();
    await page.waitForTimeout(1200);
    assert.equal(await timer.textContent(), paused);
    await page.reload();
    assert.equal(await timer.textContent(), paused,'Tempo pausado deve sobreviver à recarga');
    await page.locator('[name=status]').selectOption('criacao');
    await page.getByRole('button', {name:'Salvar status'}).click();
    await page.screenshot({path:path.join(output,'relogio-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:900});
    await page.evaluate(() => document.fonts.ready);
    await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
    await page.screenshot({path:path.join(output,'relogio-mobile.png')});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.goto(root + '/tarefas/lista/');
    await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
    await page.screenshot({path:path.join(output,'lista-mobile.png')});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.goto(root + `/catalogo/equipamentos/${fixture.equipment}/editar/`);
    await page.getByRole('link', {name:'Excluir equipamento',exact:true}).click();
    assert(await page.getByText('Este é um equipamento padrão.', {exact:false}).count());
    await page.getByRole('button', {name:'Confirmar exclusão'}).click();
    assert.equal(await page.locator(`a[href="/catalogo/equipamentos/${fixture.equipment}/"]`).count(),0);
    await page.goto(root + '/');
    assert.equal(await page.locator(`img[src="/infraestrutura/${fixture.equipment}/foto/"]`).count(),0);
    await page.goto(root + `/tarefas/${fixture.running}/`);
    assert(await page.getByText('Impressora 3D', {exact:true}).count(), 'Vínculo histórico é preservado');
    await page.goto(root + '/catalogo/equipamentos/');
    await page.getByRole('link', {name:'Restaurar equipamentos padrão'}).click();
    await page.screenshot({path:path.join(output,'restaurar-mobile.png'),fullPage:true});
    await page.getByRole('button', {name:'Confirmar restauração'}).click();
    assert(await page.locator(`a[href="/catalogo/equipamentos/${fixture.equipment}/"]`).count());
    assert(await page.getByRole('link', {name:'Equipamento personalizado de verificação',exact:true}).count());
    const noJS = await browser.newContext({javaScriptEnabled:false, viewport:{width:390,height:900}});
    await noJS.addCookies([{name:'sessionid',value:fixture.session,url:root}]);
    const fallback = await noJS.newPage();
    await fallback.goto(root + '/tarefas/lista/');
    await fallback.locator('[name=status]').selectOption('concluido');
    await fallback.getByRole('button', {name:'Aplicar filtros'}).click();
    assert(await fallback.getByText('Tarefa de verificação 0', {exact:true}).count());
    assert.equal(errors.length,0,errors.join('\n'));
    console.log('OK: relógio sem polling, pausa/recarga, quadro/lista, paginação, exclusão, restauração, desktop/móvel e fallback sem JavaScript.');
  } finally {await browser.close();}
})().catch(error => {console.error(error); process.exitCode=1;});
